"""Чистка базы от чатов, до которых уже никому нет дела.

Отдельный модуль из-за графа импортов проекта. Чистку запускают двое:
фоновый цикл в tasks.py и кнопка директора в handlers.py, а эти два модуля
друг друга не импортируют по устройству — именно это и разрывает цикл между
поллером и обработчиками. Держать две копии связки «удалить и выселить»
нельзя: разойдутся, и разойдутся тихо. Поэтому она лежит здесь, ниже обоих,
и импортирует только служебный слой (bot_cache, constants, database).

Связку нельзя разрывать ни при каких условиях. bot_cache.drop_chats()
обязана следовать за database.delete_stale_chats(), потому что гидрация
поднимает чаты в память, а callback_data с short_id живёт в уже доставленных
сообщениях Telegram неограниченно долго. Удалённый из базы, но оставшийся в
памяти чат остаётся кликабельным, и отправка в него упрётся в FK на
несуществующую строку chats.

Что эта чистка НЕ делает и почему. Она не ускоряет доставку сообщений:
список чатов для опроса приходит из Avito API (tasks.poll_account_loop), а не
из нашей базы, так что размер базы на цикл опроса не влияет вообще. Выигрыш
здесь ровно один — старт: hydrate_cache_from_db() делает по два запроса на
каждый известный чат, и эта цена растёт вместе с историей за все годы.
"""

from __future__ import annotations

import logging
from datetime import datetime

import bot_cache
import database

logger = logging.getLogger(__name__)


async def run_chat_cleanup(older_than_days: int) -> int:
    """Удалить залежавшиеся чаты, выселить их из памяти, вернуть счёт.

    Что именно считается залежавшимся — целиком в database._STALE_CHATS_WHERE,
    одним условием на удаление и на режим показа сразу, чтобы цифра, которую
    человек увидел перед нажатием, не разошлась с тем, что реально уйдёт.
    """
    deleted = await database.delete_stale_chats(older_than_days)
    if deleted:
        await bot_cache.drop_chats(deleted)
    await database.mark_chat_cleanup_done(len(deleted), datetime.utcnow())
    return len(deleted)
